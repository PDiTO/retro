"""One self-contained HTML page: every chart, the patterns, and the proposed changes.

No scripts, no fonts or stylesheets from the network. Every chart is inline SVG with a table
view of the same numbers beneath it. Every string that came from data (friction evidence,
pattern titles, diffs) is escaped, because evidence quotes whatever was in the transcript.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Sequence
from html import escape
from typing import Any

from retro.insights import Category, Insights, Proposal
from retro.viz import charts, derive
from retro.viz.theme import (
    CATEGORY_NAME,
    CATEGORY_ORDER,
    CATEGORY_SLOT,
    DARK,
    FONT,
    KIND_NAME,
    KIND_ORDER,
    LIGHT,
    MONO,
    SERIES_DARK,
    SERIES_LIGHT,
    pct,
)

SECTIONS = (
    ("overview", "Overview"),
    ("calendar", "Friction per day"),
    ("kinds", "Friction by kind"),
    ("skills", "Skills"),
    ("sessions", "Worst sessions"),
    ("flow", "From friction to fixes"),
    ("agreement", "Labelling panel"),
    ("patterns", "Patterns"),
    ("proposals", "Proposals"),
    ("cases", "Regression cases"),
    ("climb", "Hill climbing"),
)


def render_html(insights: Insights) -> str:
    start, end = derive.window(insights)
    sources = _and(insights.agents_detected) or "no sources"
    body = [
        _banner(insights),
        '<header class="masthead">',
        '<p class="eyebrow">retro report</p>',
        f"<h1>{_title(insights)}</h1>",
        f'<p class="lede">{len(insights.sessions):,} sessions from {e(sources)}, '
        f"{e(_span(start, end))}.</p>",
        _toc(),
        "</header>",
        _overview(insights),
        _calendar(insights),
        _kinds(insights),
        _skills(insights),
        _sessions(insights),
        _flow(insights),
        _agreement(insights),
        _patterns(insights),
        _proposals(insights),
        _cases(insights),
        _climb(insights),
        _footer(insights),
    ]
    return (
        '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        '<meta name="color-scheme" content="light dark">\n'
        f"<title>{e(_title(insights))} \u00b7 retro</title>\n"
        f"<style>{_CSS}</style>\n</head>\n<body>\n<main>\n"
        + "\n".join(body)
        + "\n</main>\n</body>\n</html>\n"
    )


def e(value: object) -> str:
    return escape(str(value), quote=True)


def _title(insights: Insights) -> str:
    return f"What went wrong in {insights.window_days} days of agent sessions"


def _long(value: Any) -> str:
    return f"{value.day} {value:%B %Y}"


def _span(start: Any, end: Any) -> str:
    if start.year == end.year:
        return f"{start.day} {start:%B} to {_long(end)}"
    return f"{_long(start)} to {_long(end)}"


def _and(items: Sequence[str]) -> str:
    return ", ".join(items[:-1]) + f" and {items[-1]}" if len(items) > 1 else "".join(items)


def _banner(insights: Insights) -> str:
    if not insights.synthetic:
        return ""
    return (
        '<aside class="banner" role="note"><strong>\u26a0 Synthetic demo data.</strong> '
        "Every session, project, quote and number on this page was generated by "
        "<code>retro demo</code> from a fixed seed. None of it comes from a real "
        "transcript.</aside>"
    )


def _toc() -> str:
    links = "".join(f'<li><a href="#{sid}">{e(name)}</a></li>' for sid, name in SECTIONS[1:])
    return f'<nav class="toc" aria-label="Sections"><ol>{links}</ol></nav>'


def _section(sid: str, title: str, intro: str, *content: str) -> str:
    return (
        f'<section id="{sid}">\n<h2>{e(title)}</h2>\n<p class="intro">{intro}</p>\n'
        + "\n".join(content)
        + "\n</section>"
    )


def _figure(svg: str, table: str = "") -> str:
    details = (
        f'<details class="tableview"><summary>Table view</summary>{table}</details>'
        if table
        else ""
    )
    return f'<figure class="chart">{svg}</figure>{details}'


def _table(
    headers: Sequence[str], rows: Iterable[Sequence[object]], numeric: set[int] | None = None
) -> str:
    numeric = numeric or set()
    head = "".join(
        f'<th{" class=n" if i in numeric else ""} scope="col">{e(h)}</th>'
        for i, h in enumerate(headers)
    )
    body = []
    for row in rows:
        cells = "".join(
            f"<td{' class=n' if i in numeric else ''}>{e(v)}</td>" for i, v in enumerate(row)
        )
        body.append(f"<tr>{cells}</tr>")
    if not body:
        body.append(f'<tr><td colspan="{len(headers)}" class="none">Nothing yet.</td></tr>')
    return (
        f'<div class="scroll"><table><thead><tr>{head}</tr></thead>'
        f"<tbody>{''.join(body)}</tbody></table></div>"
    )


def _overview(insights: Insights) -> str:
    sessions = len(insights.sessions)
    friction = len(insights.friction)
    with_friction = len({f.session_id for f in insights.friction})
    ag = derive.agreement(insights)
    tiles = [
        ("Sessions read", f"{sessions:,}", f"over {insights.window_days} days"),
        (
            "Friction events",
            f"{friction:,}",
            f"{100 * friction / sessions:.0f} per 100 sessions" if sessions else "no sessions",
        ),
        (
            "Sessions with friction",
            pct(with_friction / sessions) if sessions else "0%",
            f"{with_friction:,} sessions",
        ),
        (
            "Patterns",
            f"{len(insights.patterns)}",
            f"{sum(len(p.friction_ids) for p in insights.patterns):,} events grouped",
        ),
        (
            "Proposals",
            f"{len(insights.proposals)}",
            f"{len({p.target for p in insights.proposals})} files to change",
        ),
        (
            "Panel agrees",
            pct(ag.unanimous) if ag.multi else "\u2013",
            f"all {len(ag.agents)} agents, same category"
            if ag.multi
            else "needs --panel"
            if insights.labels
            else "no labels yet",
        ),
    ]
    tiles.append(
        (
            "Labels",
            f"{len(insights.labels):,}",
            f"from {len(ag.agents)} agent{'s' if len(ag.agents) != 1 else ''}",
        )
    )
    tiles.append(
        _best_climb(insights) or ("Held-out test pass rate", "\u2013", "no climb runs yet")
    )
    cells = "".join(
        f'<div class="tile"><div class="label">{e(label)}</div>'
        f'<div class="value">{e(value)}</div><div class="note">{e(note)}</div></div>'
        for label, value, note in tiles
    )
    intro = (
        "retro reads the session logs coding agents leave on disk, finds the moments the "
        "agent got it wrong, has a panel of agents label them, groups them into patterns "
        "and proposes changes to the instructions. Then it checks whether each change "
        "actually helps."
    )
    return _section("overview", "Overview", intro, f'<div class="tiles">{cells}</div>')


def _best_climb(insights: Insights) -> tuple[str, str, str] | None:
    runs = [r for r in insights.climbs if r.test_before]
    if not runs:
        return None
    gains = [
        (derive.mean(list(r.test_after.values())) - derive.mean(list(r.test_before.values())), r)
        for r in runs
    ]
    _, run = max(gains, key=lambda g: g[0])
    before = derive.mean(list(run.test_before.values()))
    after = derive.mean(list(run.test_after.values()))
    target = run.target.rsplit("/skills/", 1)[-1]
    return ("Held-out test pass rate", pct(after), f"from {pct(before)} before climbing {target}")


def _calendar(insights: Insights) -> str:
    days = derive.daily(insights)
    rows = [(f"{d:%a} {d.day} {d:%b}", s, f) for d, (f, s) in sorted(days.items()) if s or f]
    return _section(
        "calendar",
        "Friction per day",
        "A friction event is a correction, an interrupt, a refused tool call, a run of failed "
        "tool calls, a review comment or a failed check. Quiet days are only meaningful when "
        "there were sessions, so empty squares mark days with none.",
        _figure(charts.calendar(insights), _table(("Day", "Sessions", "Friction"), rows, {1, 2})),
    )


def _kinds(insights: Insights) -> str:
    weeks = derive.weekly(insights)
    kinds = [k for k in KIND_ORDER if any(w.kinds[k] for w in weeks)]
    rows = [
        (
            f"{w.start.day} {w.start:%b}",
            w.sessions,
            *(w.kinds[k] for k in kinds),
            w.total,
            f"{100 * w.total / w.sessions:.0f}" if w.sessions else "\u2013",
        )
        for w in weeks
    ]
    headers = ("Week of", "Sessions", *(KIND_NAME[k] for k in kinds), "Total", "Per 100 sessions")
    return _section(
        "kinds",
        "Friction by kind",
        "The raw count tracks how much work happened. The rate underneath divides by sessions "
        "started that week, so a busy week doesn't look like a bad one.",
        _figure(
            charts.kinds_over_time(insights),
            _table(headers, rows, set(range(1, len(headers)))),
        ),
    )


def _skills(insights: Insights) -> str:
    rows, overall, _ = derive.skill_rates(insights)
    table = _table(
        ("Skill", "Sessions", "Agent turns", "Events", "Per 100 turns", "95% interval"),
        [
            (
                r.skill,
                r.sessions,
                f"{r.turns:,}",
                r.friction,
                f"{100 * r.rate:.1f}",
                f"{100 * r.lo:.1f} to {100 * r.hi:.1f}",
            )
            for r in rows
        ],
        {1, 2, 3, 4, 5},
    )
    return _section(
        "skills",
        "Which skills go wrong most",
        "Ranking skills by event count mostly ranks them by how often they run. This divides "
        "by agent turns spent inside each skill and shows a 95% Wilson interval, so a rarely "
        "used skill with two bad sessions doesn't get called the worst on thin evidence. "
        f"The gray line is the rate across all skills, {100 * overall:.1f} per 100 turns.",
        _figure(charts.skill_scorecard(insights), table),
    )


def _sessions(insights: Insights) -> str:
    top = derive.top_sessions(insights, 12)
    rows = []
    for stats, sid, fs in top:
        mix = Counter(f.kind for f in fs)
        rows.append(
            (
                sid[:8],
                (stats.project if stats else None) or "\u2013",
                (stats.source if stats else None) or fs[0].source,
                len(fs),
                ", ".join(f"{KIND_NAME[k]} {mix[k]}" for k in KIND_ORDER if mix[k]),
            )
        )
    return _section(
        "sessions",
        "Where friction lands inside a session",
        "Clusters of ticks are a session going off the rails. Ticks spread evenly are a "
        "session where the same mistake keeps coming back. Hover a tick for the quote.",
        _figure(
            charts.session_barcode(insights),
            _table(("Session", "Project", "Source", "Events", "Kinds"), rows, {3}),
        ),
    )


def _flow(insights: Insights) -> str:
    fl = derive.flow(insights)
    targets: dict[str, str] = {}
    for (m, t), _ in fl.links_mr.items():
        targets[m] = t
    rows = [
        (CATEGORY_NAME[c], fl.titles.get(m, m), targets.get(m, "\u2013"), n)
        for (c, m), n in sorted(fl.links_lm.items(), key=lambda kv: -kv[1])
    ]
    return _section(
        "flow",
        "From friction to the file that should change",
        "Left, the category most of the labelling agents chose for each event. Middle, the "
        "recurring pattern it was grouped into. Right, the skill or instruction file the "
        "pattern points at. Thin strands crossing between categories are events the panel "
        "and the pattern disagree on.",
        _figure(
            charts.friction_flow(insights),
            _table(("Category", "Pattern", "Target", "Events"), rows, {3}),
        ),
    )


def _agreement(insights: Insights) -> str:
    ag = derive.agreement(insights)
    rows = [
        (f"{a} and {b}", shared, pct(same), f"{kappa:.2f}")
        for (a, b), (same, kappa, shared) in ag.pairs.items()
        if a < b
    ]
    present = [c for c in CATEGORY_ORDER if any(ag.mix[a][c] for a in ag.agents)]
    mix_rows = [(a, *(ag.mix[a][c] for c in present)) for a in ag.agents]
    return _section(
        "agreement",
        "How much the labelling agents agree",
        "Each event is labelled by several agents independently. Where they disagree, the "
        "category is genuinely unclear or one of them is wrong, so the disagreement rate is "
        "a ceiling on how much to trust any single label. Cohen's \u03ba corrects agreement "
        "for what two agents with these category mixes would reach by chance.",
        _figure(
            charts.agent_agreement(insights),
            _table(("Pair", "Shared events", "Agreement", "\u03ba"), rows, {1, 2, 3})
            + _table(
                ("Agent", *(CATEGORY_NAME[c] for c in present)),
                mix_rows,
                set(range(1, len(present) + 1)),
            ),
        ),
    )


def _patterns(insights: Insights) -> str:
    if not insights.patterns:
        body = (
            '<p class="empty">No patterns yet. <code>retro analyze</code> groups labelled '
            "friction into recurring patterns.</p>"
        )
        return _section(
            "patterns", "Patterns", "Recurring mistakes, grouped from labelled friction.", body
        )
    by_id = {f.id: f for f in insights.friction}
    rows = []
    for p in insights.patterns:
        example = next((by_id[i] for i in p.friction_ids if i in by_id), None)
        quote = (
            f"<blockquote>{e(example.evidence)}<cite>{e(example.id)}</cite></blockquote>"
            if example
            else ""
        )
        skill = f'<span class="skill">skill: {e(p.skill)}</span>' if p.skill else ""
        rows.append(
            "<tr>"
            f"<td><strong>{e(p.title)}</strong><p>{e(p.description)}</p>"
            f'<code class="id">{e(p.id)}</code></td>'
            f"<td>{_category_chip(p.category)}</td>"
            f'<td class="n">{len(p.friction_ids)}</td>'
            f"<td><code>{e(p.target or chr(0x2013))}</code>{skill}</td>"
            f"<td>{quote}</td>"
            "</tr>"
        )
    table = (
        '<div class="scroll"><table class="patterns"><thead><tr>'
        '<th scope="col">Pattern</th><th scope="col">Category</th>'
        '<th scope="col" class="n">Events</th>'
        '<th scope="col">Target</th><th scope="col">Example</th>'
        f"</tr></thead><tbody>{''.join(rows)}</tbody></table></div>"
    )
    return _section(
        "patterns",
        "Patterns",
        "The recurring mistakes the agents found when they grouped the labelled events, "
        "biggest first, each with one of the quotes it was built from.",
        table,
    )


def _category_chip(category: Category) -> str:
    swatch = f'<i class="sw sw{CATEGORY_SLOT[category]}"></i>'
    return f'<span class="chip">{swatch}{e(CATEGORY_NAME[category])}</span>'


def _proposals(insights: Insights) -> str:
    if not insights.proposals:
        body = (
            '<p class="empty">No proposals yet. Each pattern with a target gets a proposed '
            "edit and a draft check.</p>"
        )
        return _section("proposals", "Proposals", "Proposed changes to instructions.", body)
    titles = {p.id: p.title for p in insights.patterns}
    sizes = {p.id: len(p.friction_ids) for p in insights.patterns}
    cards = [
        _proposal(p, titles.get(p.pattern_id, p.pattern_id), sizes.get(p.pattern_id))
        for p in insights.proposals
    ]
    return _section(
        "proposals",
        "Proposed changes",
        "For each pattern, an agent drafted an edit to the instruction file and a check that "
        "would catch the mistake in a transcript. A check only becomes a regression case once "
        "it fails on the session the mistake came from.",
        *cards,
    )


def _proposal(p: Proposal, title: str, size: int | None) -> str:
    meta = [f"<code>{e(p.target)}</code>", f"proposed by {e(p.agent)}"]
    if size:
        meta.append(f"{size} events")
    return (
        '<article class="proposal">'
        f"<h3>{e(title)}</h3>"
        f'<p class="meta">{_DOT.join(meta)}</p>'
        f"<p>{e(p.rationale)}</p>"
        f'<pre class="diff" aria-label="Proposed change">{_diff(p.change)}</pre>'
        '<p class="label">Draft check</p>'
        f'<pre class="check">{_check(p.check)}</pre>'
        "</article>"
    )


_DOT = " \u00b7 "


def _diff(change: str) -> str:
    lines = []
    for line in change.rstrip("\n").split("\n"):
        if line.startswith(("+++", "---")):
            cls = "file"
        elif line.startswith("@@"):
            cls = "hunk"
        elif line.startswith("+"):
            cls = "add"
        elif line.startswith("-"):
            cls = "del"
        else:
            cls = "ctx"
        lines.append(f'<span class="{cls}">{e(line) or " "}</span>')
    return "".join(lines)  # each line is a block, so newlines would double the spacing


def _check(check: dict[str, Any]) -> str:
    """The draft check as the `[[checks]]` TOML a case file would hold."""
    out = ['<span class="hunk">[[checks]]</span>']
    keys = sorted(check, key=lambda k: (k != "type", k == "description", k))
    for key in keys:
        out.append(f'<span class="key">{e(key)}</span> = {e(_toml(check[key]))}')
    return "\n".join(out)


def _toml(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return str(value)
    text = str(value)
    if "\\" in text and "'" not in text and "\n" not in text:
        return f"'{text}'"
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def _cases(insights: Insights) -> str:
    rows = []
    for run in insights.climbs:
        for cid, row in run.grid.items():
            rows.append(
                (
                    run.target,
                    cid,
                    *(pct(row[c]) if c in row else "\u2013" for c in derive.GRID_ORDER),
                    "test" if cid in run.test_before else "",
                )
            )
    return _section(
        "cases",
        "Regression cases",
        "Each case records one mistake as checks over a transcript. The first column is the "
        "session the mistake came from, which a case has to fail before it is admitted. The "
        "next two replay the case several times with the starting instructions and with the "
        "final candidate.",
        _figure(
            charts.case_grid(insights),
            _table(
                ("Target", "Case", "Original", "Baseline", "Candidate", "Split"), rows, {2, 3, 4}
            ),
        ),
    )


def _climb(insights: Insights) -> str:
    rows = [
        (
            run.target,
            s.step,
            pct(s.train),
            pct(s.val),
            "kept" if s.accepted else "rejected",
            s.reason,
        )
        for run in insights.climbs
        for s in run.steps
    ]
    return _section(
        "climb",
        "Hill climbing the instructions",
        "Cases are split into train, val and test by a hash of their id. Each step proposes "
        "an edit from the train failures and keeps it only if val goes up and no val case "
        "gets worse. Test is scored once at the start and once at the end, and nothing in "
        "the loop sees it, so it is the honest number for whether the edits generalise.",
        _figure(
            charts.climb_chart(insights),
            _table(("Target", "Step", "Train", "Val", "Decision", "Reason"), rows, {1, 2, 3}),
        ),
    )


def _footer(insights: Insights) -> str:
    notes = [
        "Skill rates divide events by agent turns attributed to the skill. Events the "
        "labelling panel judged not a mistake are left out of them.",
        "Positions inside a session are estimated from prompt and tool-call counts, since "
        "session stats don't record a length.",
        "The panel's category for an event is the one most agents chose, with ties going "
        "to the more confident side.",
    ]
    items = "".join(f"<li>{e(n)}</li>" for n in notes)
    return (
        f"<footer><h2>Notes on method</h2><ul>{items}</ul>"
        f"<p>Generated by retro on {e(_long(insights.generated_at))}."
        f"{' Synthetic demo data.' if insights.synthetic else ''}</p></footer>"
    )


def _vars(tokens: dict[str, str], series: Sequence[str]) -> str:
    out = [f"--{k}:{v}" for k, v in tokens.items()]
    out += [f"--c{i}:{v}" for i, v in enumerate(series, start=1)]
    return ";".join(out)


